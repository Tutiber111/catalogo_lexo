// Run after changing order-template.xlsx. Invariant formula cleanup belongs at
// build time so the Edge Function only needs to edit and compress one worksheet.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {stripTypeScriptTypes} = require('node:module');
const root = path.resolve(__dirname, '..');
const fflate = require(process.env.FFLATE_MODULE || path.join(root, 'outputs/email-qa/package/lib/node.cjs'));
const directory = path.join(root, 'supabase/functions/send-order-notifications');
const context = vm.createContext({...fflate, Uint8Array, URLSearchParams, atob, btoa,
  Deno: {serve() {}, env: {get() {}}}});
vm.runInContext(stripTypeScriptTypes(fs.readFileSync(path.join(directory, 'index.ts'), 'utf8').replace(/^import .*;\r?\n/gm, '')), context);
const files = fflate.unzipSync(fs.readFileSync(path.join(directory, 'order-template.xlsx')));
context.prepareWorkbookForRecalculation(files);
const prepared = fflate.zipSync(files, {level: 1, mtime: new Date('2000-01-01T00:00:00Z')});
fs.writeFileSync(path.join(directory, 'order-template-base64.ts'),
  '// Generated by tools/prepare-order-email-template.cjs from order-template.xlsx.\n'
  + `export const ORDER_TEMPLATE_BASE64 = '${Buffer.from(prepared).toString('base64')}';\n`);
console.log(`Prepared workbook template: ${prepared.length} bytes; formulas and formatting preserved.`);
